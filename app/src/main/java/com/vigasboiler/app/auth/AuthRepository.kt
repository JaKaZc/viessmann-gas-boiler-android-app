package com.vigasboiler.app.auth

import android.content.Intent
import android.net.Uri
import androidx.core.net.toUri
import kotlin.coroutines.resume
import kotlinx.coroutines.suspendCancellableCoroutine
import net.openid.appauth.AuthorizationException
import net.openid.appauth.AuthorizationRequest
import net.openid.appauth.AuthorizationResponse
import net.openid.appauth.AuthorizationService
import net.openid.appauth.AuthorizationServiceConfiguration
import net.openid.appauth.ResponseTypeValues
import net.openid.appauth.TokenResponse
import com.vigasboiler.app.config.ApiConfig

sealed interface LoginResult {
    data object Success : LoginResult
    data object Cancelled : LoginResult
    data class Failure(val message: String) : LoginResult
}

/**
 * OAuth 2.0 Authorization Code flow with PKCE (S256, generated by AppAuth). The login page opens
 * in Chrome's Auth Tab where available: it returns the redirect straight to the app, without
 * Chrome asking "open in app?". Other browsers get AppAuth's Custom Tab flow.
 */
class AuthRepository(
    private val config: ApiConfig,
    private val authService: AuthorizationService,
    private val tokenManager: TokenManager,
    /** Whether the default browser supports Auth Tab; checked on every sign-in. */
    val authTabSupported: () -> Boolean = { false },
) {
    /** Scheme of the fixed redirect URI, which Auth Tab intercepts. */
    val redirectScheme: String = config.redirectUri.substringBefore("://")

    private val serviceConfig = AuthorizationServiceConfiguration(
        config.authorizationEndpoint.toUri(),
        config.tokenEndpoint.toUri(),
    )

    /** New request with fresh PKCE verifier and state; AppAuth carries [clientId] into the code exchange. */
    fun newRequest(clientId: String): AuthorizationRequest =
        AuthorizationRequest.Builder(
            serviceConfig,
            clientId,
            ResponseTypeValues.CODE,
            config.redirectUri.toUri(),
        ).setScope(config.scope).build()

    /** Custom Tab fallback: AppAuth's own activities receive the redirect. */
    fun customTabIntent(request: AuthorizationRequest): Intent = authService.getAuthorizationRequestIntent(request)

    /** Completes an Auth Tab sign-in from the redirect URI it returned (null: closed by the user). */
    suspend fun handleRedirect(request: AuthorizationRequest, redirect: Uri?): LoginResult {
        if (redirect == null) return LoginResult.Cancelled
        if (redirect.getQueryParameter("error") != null) {
            return LoginResult.Failure(AuthorizationException.fromOAuthRedirect(redirect).describe())
        }
        val response = AuthorizationResponse.Builder(request).fromUri(redirect).build()
        // AppAuth's own activity checks this in the Custom Tab flow; here it is up to us.
        if (response.state != request.state) return LoginResult.Failure("Sign-in response does not belong to this request")
        return complete(response)
    }

    suspend fun handleAuthorizationResult(data: Intent?): LoginResult {
        if (data == null) return LoginResult.Cancelled
        val response = AuthorizationResponse.fromIntent(data)
        val error = AuthorizationException.fromIntent(data)
        if (response == null) {
            return if (error == null || error == AuthorizationException.GeneralErrors.USER_CANCELED_AUTH_FLOW) {
                LoginResult.Cancelled
            } else {
                LoginResult.Failure(error.describe())
            }
        }
        return complete(response)
    }

    private suspend fun complete(response: AuthorizationResponse): LoginResult {
        val token = exchangeCode(response).getOrElse { e ->
            return LoginResult.Failure((e as? AuthorizationException)?.describe() ?: e.message.orEmpty())
        }
        val access = token.accessToken ?: return LoginResult.Failure("Token response contained no access token")
        val refresh = token.refreshToken
            ?: return LoginResult.Failure("Token response contained no refresh token. Is the scope missing offline_access?")
        tokenManager.onSignedIn(
            Tokens(
                accessToken = access,
                refreshToken = refresh,
                expiresAtMillis = token.accessTokenExpirationTime ?: (System.currentTimeMillis() + 3_600_000L),
            ),
        )
        return LoginResult.Success
    }

    private suspend fun exchangeCode(response: AuthorizationResponse): Result<TokenResponse> =
        suspendCancellableCoroutine { cont ->
            authService.performTokenRequest(response.createTokenExchangeRequest()) { tokenResponse, ex ->
                cont.resume(
                    when {
                        tokenResponse != null -> Result.success(tokenResponse)
                        else -> Result.failure(ex ?: IllegalStateException("Token exchange failed"))
                    },
                )
            }
        }

    private fun AuthorizationException.describe(): String =
        listOfNotNull(error, errorDescription).joinToString(": ").ifBlank { "Authorization failed (code $code)" }
}
